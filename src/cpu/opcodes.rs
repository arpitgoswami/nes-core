/// Indexed reads pay one extra cycle when crossing a page boundary.
pub fn is_read_instruction(op: Op) -> bool {
    !matches!(
        op,
        Op::Sta
            | Op::Stx
            | Op::Sty
            | Op::Sax
            | Op::Asl
            | Op::Lsr
            | Op::Rol
            | Op::Ror
            | Op::Inc
            | Op::Dec
            | Op::Slo
            | Op::Rla
            | Op::Sre
            | Op::Rra
            | Op::Dcp
            | Op::Isc
            | Op::Jam
            | Op::Brk
            | Op::Jmp
            | Op::Jsr
            | Op::Rts
            | Op::Rti
    )
}
